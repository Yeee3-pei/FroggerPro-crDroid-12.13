def validate():
    for ch, rows in F.items():
        assert len(rows) == 5, f"{ch!r}: {len(rows)} rows"
        for r in rows:
            assert len(r) == 5, f"{ch!r}: row {r!r}"
            assert set(r) <= {'#', '.'}, f"{ch!r}: row {r!r}"
    seen = {}
    for ch, rows in sorted(F.items()):
        if ch == ' ':
            continue
        key = "".join(rows)
        if key in seen and {ch, seen[key]} != {'O', '0'}:
            raise AssertionError(f"{ch!r} is identical to {seen[key]!r}")
        seen[key] = ch

