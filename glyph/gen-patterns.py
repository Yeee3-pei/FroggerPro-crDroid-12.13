"""Generates the Glyph Matrix notification and call patterns.

Each pattern is a CSV under FroggerPro/assets/{notif,ring}/: one frame
per line, GlyphMatrix.COUNT (137) brightness values 0-255 in the driver's
row-major order, trailing comma. AnimationManager.playCsv() plays them at
~60 fps; ring patterns loop for as long as the phone rings. The pattern
pickers list whatever files are in those directories, so a new pattern here
is a new choice in Settings with no code change.

Ripple.csv (ring) predates this script and is not regenerated by it.

    ./gen-patterns.py          # rewrite every pattern below
"""
import math
import os
import random

SIDE = 13
C = (SIDE - 1) / 2
RADIUS_SQ = 42          # 6.5^2 = 42.25; must match GlyphMatrix.RADIUS_SQ
FPS = 60
MAX = 255

CELLS = [(x, y) for y in range(SIDE) for x in range(SIDE)
         if (x - C) ** 2 + (y - C) ** 2 <= RADIUS_SQ]
assert len(CELLS) == 137, len(CELLS)
R = [math.hypot(x - C, y - C) for x, y in CELLS]
# 0 at 12 o'clock, increasing clockwise, in [0, 2pi)
A = [math.atan2(x - C, -(y - C)) % (2 * math.pi) for x, y in CELLS]
RIM = max(R)

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "FroggerPro", "assets")


def frames(seconds):
    return int(round(seconds * FPS))


def clamp(v):
    return max(0, min(MAX, int(round(v))))


def ease(t):
    """sin^2 bump over t in [0,1]: 0 -> 1 -> 0."""
    return math.sin(math.pi * max(0.0, min(1.0, t))) ** 2


def angdist(a, b):
    d = abs(a - b) % (2 * math.pi)
    return min(d, 2 * math.pi - d)


def solid(level):
    return [clamp(level)] * len(CELLS)


# ---- notification patterns (one shot) ------------------------------------

def pulse():
    breath = [solid(MAX * ease(i / 53)) for i in range(54)]
    return breath + [solid(0)] * 15 + breath + [solid(0)]


def ripple_out():
    """"Wave" in the picker: rings expanding from the centre, twice."""
    out = []
    for _ in range(2):
        n = frames(0.8)
        for i in range(n):
            front = (i / (n - 1)) * (RIM + 1.5)
            fade = 1 - 0.5 * i / n
            out.append([clamp(MAX * fade * max(0.0, 1 - abs(r - front) / 1.2)) for r in R])
        out += [solid(0)] * frames(0.15)
    return out + [solid(0)]


def comet():
    out = []
    n = frames(1.4)
    tail = math.pi * 0.9
    for i in range(n):
        head = 2 * math.pi * i / n
        f = []
        for r, a in zip(R, A):
            if r < RIM - 1.6:
                f.append(0)
                continue
            behind = (head - a) % (2 * math.pi)
            f.append(clamp(MAX * (1 - behind / tail)) if behind <= tail else 0)
        out.append(f)
    return out + [solid(0)]


def blink():
    on = [solid(MAX)] * frames(0.12)
    off = [solid(0)] * frames(0.18)
    return on + off + on + [solid(0)]


def sparkle():
    rnd = random.Random(4)
    n = frames(1.6)
    starts = [(rnd.randrange(len(CELLS)), rnd.randrange(n - 20)) for _ in range(70)]
    out = []
    for i in range(n):
        f = [0] * len(CELLS)
        for cell, t0 in starts:
            t = (i - t0) / 20
            if 0 <= t <= 1:
                f[cell] = max(f[cell], clamp(MAX * ease(t)))
        out.append(f)
    return out + [solid(0)]


# ---- call patterns (looped while ringing) --------------------------------

def radar():
    n = frames(1.5)
    trail = math.pi * 0.8
    out = []
    for i in range(n):
        arm = 2 * math.pi * i / n
        f = []
        for r, a in zip(R, A):
            behind = (arm - a) % (2 * math.pi)
            lvl = MAX * (1 - behind / trail) if behind <= trail else 0
            f.append(clamp(max(lvl, MAX * 0.25 if r < 0.8 else 0)))
        out.append(f)
    return out


def heartbeat():
    def beat(peak, length):
        return [solid(peak * ease(i / (length - 1))) for i in range(length)]
    return (beat(MAX, frames(0.22)) + [solid(0)] * frames(0.08)
            + beat(MAX * 0.7, frames(0.22)) + [solid(0)] * frames(0.65))


def orbit():
    n = frames(1.2)
    out = []
    for i in range(n):
        heads = [2 * math.pi * i / n, 2 * math.pi * i / n + math.pi]
        f = []
        for r, a in zip(R, A):
            if r < RIM - 1.6:
                f.append(0)
                continue
            d = min(angdist(a, h) for h in heads)
            f.append(clamp(MAX * max(0.0, 1 - d / 0.45)))
        out.append(f)
    return out


def breathe():
    n = frames(2.0)
    return [solid(MAX * (0.08 + 0.92 * ease(i / n))) for i in range(n)]


PATTERNS = {
    "notif": {
        "Pulse": pulse,
        "Wave": ripple_out,
        "Comet": comet,
        "Blink": blink,
        "Sparkle": sparkle,
    },
    "ring": {
        "Radar": radar,
        "Heartbeat": heartbeat,
        "Orbit": orbit,
        "Breathe": breathe,
    },
}


def main():
    for kind, table in PATTERNS.items():
        for name, fn in table.items():
            data = fn()
            assert data and all(len(f) == 137 for f in data), name
            path = os.path.join(ASSETS, kind, name + ".csv")
            with open(path, "w") as out:
                out.write("\n".join(",".join(map(str, f)) + "," for f in data) + "\n")
            print(f"{kind}/{name}.csv: {len(data)} frames, {len(data) / FPS:.2f} s")


if __name__ == "__main__":
    main()
